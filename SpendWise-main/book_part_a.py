DATE = "אב תשפ״ו — אוקטובר 2026"


def cover(doc):
    for _ in range(3):
        doc.add_paragraph()

    P(doc, "ספר פרויקט", size=30, bold=True, color=ACCENT,
      align=WD_ALIGN_PARAGRAPH.CENTER, space_after=4)
    P(doc, "„שקלול”  —  SpendWise", size=22, bold=True,
      align=WD_ALIGN_PARAGRAPH.CENTER, space_after=2)
    P(doc, "מערכת חכמה לניהול כלכלת הבית, לניתוח מצב פיננסי ולהפקת המלצות תקציביות",
      size=13, color=MUTED, align=WD_ALIGN_PARAGRAPH.CENTER, space_after=40)

    t = doc.add_table(rows=0, cols=2)
    t.style = "Light List Accent 1"
    data = [
        ("שם התלמידות", f"{STUDENT1}  |  {STUDENT2}"),
        ("תעודת זהות", f"{ID1}  |  {ID2}"),
        ("מסגרת הלימודים", SEMINAR),
        ("מנחה", ADVISOR),
        ("תאריך הגשה", DATE),
    ]
    for k, v in data:
        cells = t.add_row().cells
        for cell, txt, bold in ((cells[0], k, True), (cells[1], v, False)):
            cell.text = ""
            p = cell.paragraphs[0]
            r = p.add_run(txt)
            r.font.name = HEBREW_FONT
            r.font.size = Pt(12)
            r.font.bold = bold
            from build_book_docx import set_rtl
            set_rtl(p)
    for row in t.rows:
        row.cells[0].width = __import__("docx").shared.Cm(4.5)
        row.cells[1].width = __import__("docx").shared.Cm(10)

    doc.add_page_break()


